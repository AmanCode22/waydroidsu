pub const RC_BLOCK: &str = r#"# >>> wsu (WaydroidSU) KitsuneMagisk bootstrap >>>
on post-fs-data
    start logd
    exec u:r:su:s0 root root -- /system/bin/sh /system/etc/init/magisk/wsu_boot.sh post-fs-data

service wsu_magisk_svc /system/etc/init/magisk/wsu_boot.sh service
    class late_start
    user root
    seclabel u:r:su:s0
    oneshot

on property:sys.boot_completed=1
    exec u:r:su:s0 root root -- /system/etc/init/magisk/wsu_boot.sh boot-complete

on property:init.svc.zygote=restarting
    exec u:r:su:s0 root root -- /system/etc/init/magisk/wsu_boot.sh zygote-restart
# <<< wsu (WaydroidSU) KitsuneMagisk bootstrap <<<
"#;

