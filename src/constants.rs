/// Boot bootstrap executed inside the container by the injected rc block.
/// Mirrors the fork's supported scripts/live_setup.sh flow for writable
/// targets: stage payload into /data/adb/magisk, set up /sbin, then run the
/// requested daemon stage. Idempotent — safe to run on every boot.
pub const WSU_BOOT_SH: &str = r#"#!/system/bin/sh
# WaydroidSU (wsu) KitsuneMagisk boot bootstrap — generated by wsu, do not edit.
MD=/system/etc/init/magisk
MT=/sbin
ADB=/data/adb
stage="$1"

[ -x "$MD/magisk" ] || exit 0

mkdir -p "$MT/.magisk/worker" "$MT/.magisk/device" \
         "$ADB/magisk" "$ADB/modules" "$ADB/post-fs-data.d" "$ADB/service.d" \
         "$ADB/post-fs-data.d"

if ! grep -q " $MT/.magisk/worker " /proc/mounts 2>/dev/null; then
  mount -t tmpfs -o 'mode=0755' tmpfs "$MT/.magisk/worker" 2>/dev/null
  mount --make-private "$MT/.magisk/worker" 2>/dev/null
fi

if [ ! -f "$ADB/magisk/magisk" ] || ! cmp -s "$MD/magisk" "$ADB/magisk/magisk"; then
  for f in magisk magisk32 magiskpolicy magiskinit magiskboot busybox init-ld \
           stub.apk util_functions.sh module_installer.sh boot_patch.sh \
           flash_script.sh uninstaller.sh update_binary.sh addon.d.sh app_functions.sh; do
    if [ -f "$MD/$f" ]; then
      cp -af "$MD/$f" "$ADB/magisk/$f" && chmod 0755 "$ADB/magisk/$f"
    fi
  done
fi

for f in magisk magiskpolicy busybox; do
  cp -af "$MD/$f" "$MT/$f" && chmod 0755 "$MT/$f"
done
ln -sf magisk "$MT/su"
ln -sf magisk "$MT/resetprop"
ln -sf magiskpolicy "$MT/supolicy"
[ -f "$MT/.magisk/config" ] || touch "$MT/.magisk/config"
touch "$MT/.magisk/live"
export MAGISKTMP="$MT"

case "$stage" in
  post-fs-data)    exec "$MT/magisk" --post-fs-data ;;
  service)         exec "$MT/magisk" --service ;;
  boot-complete)   exec "$MT/magisk" --boot-complete ;;
  zygote-restart)  exec "$MT/magisk" --zygote-restart ;;
  *)               exit 0 ;;
esac
"#;
